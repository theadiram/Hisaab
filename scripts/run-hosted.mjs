import { spawn } from 'node:child_process';
process.loadEnvFile('.env.hosted');
if (!process.env.SUPABASE_SECRET_KEY) throw new Error('Hosted server connection is not configured');
const command = process.argv[2] ?? 'dev';
if (!['dev', 'build', 'start'].includes(command)) throw new Error('Choose dev, build or start');
const args = ['node_modules/next/dist/bin/next', command];
if (command !== 'build') args.push('--hostname', '127.0.0.1');
args.push(...process.argv.slice(3));
const child = spawn(process.execPath, args, { stdio: 'inherit', env: process.env });
for (const signal of ['SIGINT', 'SIGTERM']) process.on(signal, () => child.kill(signal));
child.on('exit', (code) => process.exit(code ?? 1));
